-- SS AUCTION Guardian error log. Only server-side service_role can access it.
CREATE TABLE IF NOT EXISTS public.guardian_errors (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operation TEXT NOT NULL,
  severity TEXT NOT NULL CHECK (severity IN ('medium', 'high', 'critical')),
  message TEXT NOT NULL,
  room_id TEXT,
  source TEXT NOT NULL DEFAULT 'server',
  fingerprint TEXT,
  status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'investigating', 'resolved')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  resolved_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS guardian_errors_created_at_idx ON public.guardian_errors (created_at DESC);
CREATE INDEX IF NOT EXISTS guardian_errors_status_created_at_idx ON public.guardian_errors (status, created_at DESC);
ALTER TABLE public.guardian_errors ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.guardian_errors FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON TABLE public.guardian_errors TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.guardian_errors_id_seq TO service_role;
