-- SS AUCTION INSIGHTS Phase 2: minute-level concurrency snapshots.
-- Run this migration in the Supabase SQL Editor after the Phase 1 schema.
-- Snapshots contain aggregate counts only; no user identifiers or IP addresses.

CREATE TABLE IF NOT EXISTS public.analytics_presence_snapshots (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sampled_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  online_players INTEGER NOT NULL DEFAULT 0 CHECK (online_players >= 0),
  active_players INTEGER NOT NULL DEFAULT 0 CHECK (active_players >= 0),
  active_rooms INTEGER NOT NULL DEFAULT 0 CHECK (active_rooms >= 0)
);

CREATE INDEX IF NOT EXISTS analytics_presence_sampled_at_idx
  ON public.analytics_presence_snapshots (sampled_at DESC);

ALTER TABLE public.analytics_presence_snapshots ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.analytics_presence_snapshots FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT ON public.analytics_presence_snapshots TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.analytics_presence_snapshots_id_seq TO service_role;
