-- SS AUCTION INSIGHTS: private analytics foundation
-- Apply this migration in the Supabase SQL Editor.
-- Raw analytics are accessible only to the server-side service_role.

CREATE TABLE IF NOT EXISTS public.analytics_sessions (
  session_id UUID PRIMARY KEY,
  firebase_uid TEXT NOT NULL,
  is_anonymous BOOLEAN NOT NULL DEFAULT FALSE,
  started_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  ended_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS analytics_sessions_started_at_idx
  ON public.analytics_sessions (started_at DESC);
CREATE INDEX IF NOT EXISTS analytics_sessions_uid_started_idx
  ON public.analytics_sessions (firebase_uid, started_at DESC);
CREATE INDEX IF NOT EXISTS analytics_sessions_last_seen_idx
  ON public.analytics_sessions (last_seen_at DESC);

CREATE TABLE IF NOT EXISTS public.analytics_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id UUID REFERENCES public.analytics_sessions(session_id) ON DELETE SET NULL,
  firebase_uid TEXT NOT NULL,
  event_name TEXT NOT NULL CHECK (event_name IN (
    'page_view', 'room_join', 'room_leave', 'auction_start',
    'bid', 'chat_message', 'voice_join', 'voice_leave'
  )),
  room_id TEXT,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE INDEX IF NOT EXISTS analytics_events_occurred_at_idx
  ON public.analytics_events (occurred_at DESC);
CREATE INDEX IF NOT EXISTS analytics_events_name_time_idx
  ON public.analytics_events (event_name, occurred_at DESC);
CREATE INDEX IF NOT EXISTS analytics_events_uid_time_idx
  ON public.analytics_events (firebase_uid, occurred_at DESC);
CREATE INDEX IF NOT EXISTS analytics_events_room_time_idx
  ON public.analytics_events (room_id, occurred_at DESC)
  WHERE room_id IS NOT NULL;

ALTER TABLE public.analytics_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.analytics_events ENABLE ROW LEVEL SECURITY;

-- No browser/client role may read or write analytics, even if it knows a row ID.
REVOKE ALL ON TABLE public.analytics_sessions FROM PUBLIC, anon, authenticated;
REVOKE ALL ON TABLE public.analytics_events FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.analytics_sessions TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE public.analytics_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.analytics_events_id_seq TO service_role;

COMMENT ON TABLE public.analytics_sessions IS
  'Private SS AUCTION visitor sessions. Firebase UID is retained only for distinct-user counting.';
COMMENT ON TABLE public.analytics_events IS
  'Private, timestamped SS AUCTION activity events. Do not store email, display name, IP, or message contents.';
